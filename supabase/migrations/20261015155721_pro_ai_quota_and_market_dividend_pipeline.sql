create or replace function public.verify_market_sync_token(p_token text)
returns boolean
language sql
stable
security definer
set search_path = public, vault, pg_temp
as $$
  select length(coalesce(p_token, '')) >= 32
    and exists (
      select 1 from vault.decrypted_secrets
      where name = 'market_sync_cron_token' and decrypted_secret = p_token
    );
$$;
revoke all on function public.verify_market_sync_token(text) from public, anon, authenticated;
grant execute on function public.verify_market_sync_token(text) to service_role;

