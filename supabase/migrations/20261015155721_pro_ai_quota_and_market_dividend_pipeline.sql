create or replace function public.consume_financial_ai_quota()
returns table(allowed boolean, call_count integer, daily_limit integer)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_count integer;
  v_limit constant integer := 40;
begin
  if v_uid is null or coalesce((auth.jwt() ->> 'is_anonymous')::boolean, false) then
    raise exception 'authenticated member required' using errcode = '42501';
  end if;
  insert into public.financial_ai_usage_daily(usage_date, client_hash, call_count, updated_at)
  values (current_date, v_uid::text, 1, now())
  on conflict (usage_date, client_hash) do update
    set call_count = public.financial_ai_usage_daily.call_count + 1,
        updated_at = now()
  returning financial_ai_usage_daily.call_count into v_count;
  return query select v_count <= v_limit, v_count, v_limit;
end;
$$;
revoke all on function public.consume_financial_ai_quota() from public, anon;
grant execute on function public.consume_financial_ai_quota() to authenticated;

